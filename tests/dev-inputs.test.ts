test('unresolved Git index stages are unavailable', async (t) => {
  const root = await fixture(t);
  const blob = git(root, ['rev-parse', 'HEAD:src/index.ts']);
  git(root, ['update-index', '--index-info'], `0 ${'0'.repeat(40)}\tsrc/index.ts\n100644 ${blob} 1\tsrc/index.ts\n100644 ${blob} 2\tsrc/index.ts\n`);
  const result = await captureInputs(root);
  assert.equal(result.available, false);
  assert.match(result.reason, /unresolved/i);
});

