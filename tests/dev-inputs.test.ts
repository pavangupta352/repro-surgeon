test('unavailable or malformed saved fingerprints never compare as fresh', async (t) => {
  const root = await fixture(t);
  const before = await captureInputs(root);
  for (const invalid of [undefined, {}, { ...before, tree: null }, { ...before, policy: 'other' }, { ...before, root: root + '/other' }, { ...before, stalegreen: { available: true, tree: null } }, { ...before, head: null }, { ...before, tree: [before.tree] }, { ...before, head: [before.head] }, { ...before, stalegreen: { ...before.stalegreen, tree: [before.stalegreen.tree] } }]) {
    assert.equal(compareInputs(before, invalid), 'unknown');
  }
});


test('linked worktrees retain their own root and full HEAD', async (t) => {
  const root = await fixture(t);
  const parent = await mkdtemp(join(tmpdir(), 'repro-linked-inputs-'));
  t.after(() => rm(parent, { recursive: true, force: true }));
  const linked = join(parent, 'checkout');
  git(root, ['worktree', 'add', '--detach', linked, 'HEAD']);
  const result = await captureInputs(linked);
  assert.equal(result.available, true, result.reason);
  assert.equal(result.root, await realpath(linked));
  assert.equal(result.head, git(root, ['rev-parse', 'HEAD']));
});

test('missing Git cannot silently degrade to a fresh filesystem hash', async (t) => {
  const root = await fixture(t);
  const module = new URL('../scripts/verification/inputs.mjs', import.meta.url).href;
  const output = execFileSync(process.execPath, ['--input-type=module', '-e',
    `import { captureInputs } from ${JSON.stringify(module)}; console.log(JSON.stringify(await captureInputs(${JSON.stringify(root)})));`,
  ], { encoding: 'utf8', env: { ...process.env, PATH: '' } });
  const result = JSON.parse(output);
  assert.equal(result.available, false);
  assert.equal(result.tree, null);
  assert.match(result.reason, /git.*unavailable/i);
});

